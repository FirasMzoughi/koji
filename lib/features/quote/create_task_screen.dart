import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:koji/features/quote/repository/task_repository.dart';
import 'package:koji/features/pricing/repository/pricing_repository.dart';
import 'package:koji/features/auth/repository/user_repository.dart';
import 'package:koji/features/auth/repository/auth_repository.dart';

class CreateTaskScreen extends ConsumerStatefulWidget {
  final String profession;
  final String? parentId;
  final String? parentCode;

  const CreateTaskScreen({
    super.key,
    required this.profession,
    this.parentId,
    this.parentCode,
  });

  @override
  ConsumerState<CreateTaskScreen> createState() => _CreateTaskScreenState();
}

class _CreateTaskScreenState extends ConsumerState<CreateTaskScreen> {
  final _formKey = GlobalKey<FormState>();

  final _codeController        = TextEditingController();
  final _designationController = TextEditingController();
  final _commentaireController = TextEditingController();

  String _selectedFamille = 'Carrelage';
  String _selectedUnite   = 'm²';
  bool   _isSaving        = false;

  double _tauxHoraire = 56.25;

  static const List<String> _familles = [
    'Carrelage', 'Peinture', 'Plomberie',
    'Electricité', 'Menuiserie', 'Démolition', 'Autre',
  ];
  static const List<String> _unites = ['m²', 'ml', 'u', 'h', 'forfait'];

  @override
  void initState() {
    super.initState();
    _loadTauxHoraire();
  }

  @override
  void dispose() {
    _codeController.dispose();
    _designationController.dispose();
    _commentaireController.dispose();
    super.dispose();
  }

  Future<void> _loadTauxHoraire() async {
    try {
      if (widget.profession.isNotEmpty) {
        final profile = await ref
            .read(pricingRepositoryProvider)
            .getProfileForProfession(widget.profession);
        if (profile != null && profile.hoursPerDay > 0) {
          if (mounted) setState(() => _tauxHoraire = profile.hourlyRate);
          return;
        }
      }
      final user = ref.read(authRepositoryProvider).currentUser;
      if (user == null) return;
      final userData = await ref.read(userRepositoryProvider).getUser(user.id);
      final biz = userData?['business_info'] as Map<String, dynamic>?;
      if (biz != null) {
        final daily = (biz['dailyRate'] as num?)?.toDouble() ?? 450.0;
        final hours = (biz['hoursPerDay'] as num?)?.toDouble() ?? 8.0;
        if (mounted) setState(() => _tauxHoraire = hours > 0 ? daily / hours : 56.25);
      }
    } catch (_) {}
  }

  bool get _isSubTask => widget.parentId != null;

  Future<void> _saveTask() async {
    if (!_formKey.currentState!.validate()) return;
    setState(() => _isSaving = true);
    try {
      await ref.read(taskRepositoryProvider).createTask(
        title:       _designationController.text.trim(),
        description: _commentaireController.text.trim().isNotEmpty
            ? _commentaireController.text.trim()
            : null,
        profession:  widget.profession,
        code:        _isSubTask
            ? null   // auto-generated by repository
            : (_codeController.text.trim().isNotEmpty
                ? _codeController.text.trim()
                : null),
        famille: _selectedFamille,
        unite:   _selectedUnite,
        parentId: widget.parentId,
        typePoste: _isSubTask ? 'SOUS-POSTE' : 'POSTE',
        // tempsHU is NOT stored on the task — entered per-devis
      );
      if (mounted) Navigator.pop(context, true);
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context)
          .showSnackBar(SnackBar(content: Text('Erreur: $e')));
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFFF8F9FA),
      appBar: AppBar(
        title: Text(
          _isSubTask ? 'Nouveau sous-poste' : 'Nouvelle tâche',
          style: const TextStyle(fontWeight: FontWeight.bold, color: Color(0xFF0F172A)),
        ),
        backgroundColor: Colors.white,
        elevation: 0,
        iconTheme: const IconThemeData(color: Color(0xFF0F172A)),
        bottom: PreferredSize(
          preferredSize: const Size.fromHeight(1),
          child: Container(height: 1, color: const Color(0xFFE2E8F0)),
        ),
      ),
      body: Form(
        key: _formKey,
        child: ListView(
          padding: const EdgeInsets.fromLTRB(20, 20, 20, 120),
          children: [
            // ── Info header ───────────────────────────────────────────
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: const Color(0xFF0F172A),
                borderRadius: BorderRadius.circular(12),
              ),
              child: Row(
                children: [
                  const Icon(Icons.timer_outlined, color: Color(0xFFEAD8B1), size: 18),
                  const SizedBox(width: 10),
                  Expanded(
                    child: Text(
                      'Taux horaire : ${_tauxHoraire.toStringAsFixed(2)} €/h  •  ${widget.profession}',
                      style: const TextStyle(color: Color(0xFFCBD5E1), fontSize: 13),
                    ),
                  ),
                ],
              ),
            ),

            const SizedBox(height: 8),

            // Note: temps h/u is entered when using the task in a devis
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
              decoration: BoxDecoration(
                color: const Color(0xFFFFFBEB),
                borderRadius: BorderRadius.circular(10),
                border: Border.all(color: const Color(0xFFFDE68A)),
              ),
              child: const Row(
                children: [
                  Icon(Icons.info_outline, size: 15, color: Color(0xFFB45309)),
                  SizedBox(width: 8),
                  Expanded(
                    child: Text(
                      'Le temps h/unité sera saisi lors de la création du devis, car il peut varier selon le chantier.',
                      style: TextStyle(fontSize: 12, color: Color(0xFF92400E)),
                    ),
                  ),
                ],
              ),
            ),

            const SizedBox(height: 24),

            // ── Sub-task parent indicator ─────────────────────────────
            if (_isSubTask) ...[
              Container(
                padding: const EdgeInsets.all(12),
                decoration: BoxDecoration(
                  color: const Color(0xFFF0F9FF),
                  borderRadius: BorderRadius.circular(10),
                  border: Border.all(color: const Color(0xFFBAE6FD)),
                ),
                child: Row(
                  children: [
                    const Icon(Icons.account_tree, size: 16, color: Color(0xFF0369A1)),
                    const SizedBox(width: 8),
                    Expanded(
                      child: Text(
                        'Sous-poste de ${widget.parentCode ?? "parent"}',
                        style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600, color: Color(0xFF0369A1)),
                      ),
                    ),
                    Container(
                      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                      decoration: BoxDecoration(
                        color: const Color(0xFF0369A1).withValues(alpha: 0.1),
                        borderRadius: BorderRadius.circular(6),
                      ),
                      child: const Text(
                        'Réf. auto',
                        style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold, color: Color(0xFF0369A1)),
                      ),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 18),
            ],

            // ── CODE (hidden for sub-tasks — auto-generated) ─────────
            if (!_isSubTask) ...[
              _sectionLabel('Code'),
              const SizedBox(height: 6),
              _buildTextField(
                controller: _codeController,
                hint: 'ex: CAR-01, PLO-03…',
                onChanged: (_) => setState(() {}),
              ),
              const SizedBox(height: 18),
            ],

            // ── DÉSIGNATION ──────────────────────────────────────────
            _sectionLabel('Désignation *'),
            const SizedBox(height: 6),
            _buildTextField(
              controller: _designationController,
              hint: 'ex: Pose carrelage sol ≤ 60×60 cm',
              onChanged: (_) => setState(() {}),
              validator: (v) =>
                  (v == null || v.trim().isEmpty) ? 'Désignation requise' : null,
            ),

            const SizedBox(height: 18),

            // ── FAMILLE ──────────────────────────────────────────────
            _sectionLabel('Famille *'),
            const SizedBox(height: 6),
            _buildDropdownRow(
              value: _selectedFamille,
              items: _familles,
              onChanged: (v) => setState(() => _selectedFamille = v!),
              color: _familleColor(_selectedFamille),
            ),

            const SizedBox(height: 18),

            // ── UNITÉ ────────────────────────────────────────────────
            _sectionLabel('Unité *'),
            const SizedBox(height: 6),
            _buildDropdownRow(
              value: _selectedUnite,
              items: _unites,
              onChanged: (v) => setState(() => _selectedUnite = v!),
              color: const Color(0xFF475569),
            ),

            const SizedBox(height: 18),

            // ── COMMENTAIRE ──────────────────────────────────────────
            _sectionLabel('Commentaire'),
            const SizedBox(height: 6),
            _buildTextField(
              controller: _commentaireController,
              hint: 'ex: Colle + joints inclus, fourniture en sus…',
              maxLines: 3,
              onChanged: (_) => setState(() {}),
            ),

            const SizedBox(height: 24),

            // ── Preview card ─────────────────────────────────────────
            if (_designationController.text.trim().isNotEmpty) ...[
              Container(
                padding: const EdgeInsets.all(16),
                decoration: BoxDecoration(
                  color: const Color(0xFFEFF6FF),
                  borderRadius: BorderRadius.circular(14),
                  border: Border.all(color: const Color(0xFFBFDBFE)),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        Container(
                          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                          decoration: BoxDecoration(
                            color: _familleColor(_selectedFamille).withValues(alpha: 0.12),
                            borderRadius: BorderRadius.circular(6),
                          ),
                          child: Text(
                            _codeController.text.trim().isNotEmpty
                                ? _codeController.text.trim()
                                : _selectedFamille.substring(0, 3).toUpperCase(),
                            style: TextStyle(
                              fontSize: 11,
                              fontWeight: FontWeight.bold,
                              color: _familleColor(_selectedFamille),
                            ),
                          ),
                        ),
                        const SizedBox(width: 8),
                        Text(
                          _selectedFamille,
                          style: const TextStyle(fontSize: 12, color: Color(0xFF94A3B8)),
                        ),
                        const Spacer(),
                        Container(
                          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                          decoration: BoxDecoration(
                            color: const Color(0xFF475569).withValues(alpha: 0.08),
                            borderRadius: BorderRadius.circular(6),
                          ),
                          child: Text(
                            _selectedUnite,
                            style: const TextStyle(
                              fontSize: 11,
                              fontWeight: FontWeight.w600,
                              color: Color(0xFF475569),
                            ),
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 8),
                    Text(
                      _designationController.text.trim(),
                      style: const TextStyle(
                        fontSize: 15,
                        fontWeight: FontWeight.bold,
                        color: Color(0xFF0F172A),
                      ),
                    ),
                    if (_commentaireController.text.trim().isNotEmpty) ...[
                      const SizedBox(height: 4),
                      Text(
                        _commentaireController.text.trim(),
                        style: const TextStyle(fontSize: 12, color: Color(0xFF94A3B8)),
                      ),
                    ],
                    const SizedBox(height: 10),
                    const Divider(height: 1, color: Color(0xFFBFDBFE)),
                    const SizedBox(height: 10),
                    Row(
                      children: [
                        const Icon(Icons.access_time, size: 13, color: Color(0xFF3B82F6)),
                        const SizedBox(width: 5),
                        Text(
                          'Temps h/$_selectedUnite : à saisir dans le devis',
                          style: const TextStyle(fontSize: 12, color: Color(0xFF3B82F6)),
                        ),
                      ],
                    ),
                  ],
                ),
              ),
            ],
          ],
        ),
      ),

      bottomSheet: Container(
        decoration: const BoxDecoration(
          color: Colors.white,
          border: Border(top: BorderSide(color: Color(0xFFE2E8F0))),
        ),
        padding: const EdgeInsets.fromLTRB(20, 14, 20, 32),
        child: SafeArea(
          top: false,
          child: SizedBox(
            width: double.infinity,
            height: 52,
            child: ElevatedButton(
              onPressed: _isSaving ? null : _saveTask,
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF0F172A),
                foregroundColor: Colors.white,
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
              ),
              child: _isSaving
                  ? const SizedBox(
                      width: 22, height: 22,
                      child: CircularProgressIndicator(color: Colors.white, strokeWidth: 2),
                    )
                  : Text(
                      _isSubTask ? 'Ajouter le sous-poste' : 'Enregistrer la tâche',
                      style: const TextStyle(fontSize: 15, fontWeight: FontWeight.bold),
                    ),
            ),
          ),
        ),
      ),
    );
  }

  Widget _sectionLabel(String label) => Text(
    label,
    style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600, color: Color(0xFF374151)),
  );

  Widget _buildTextField({
    required TextEditingController controller,
    required String hint,
    int maxLines = 1,
    TextInputType keyboardType = TextInputType.text,
    void Function(String)? onChanged,
    String? Function(String?)? validator,
  }) {
    return TextFormField(
      controller: controller,
      maxLines: maxLines,
      keyboardType: keyboardType,
      onChanged: onChanged,
      validator: validator,
      decoration: InputDecoration(
        hintText: hint,
        hintStyle: const TextStyle(color: Color(0xFF94A3B8), fontSize: 14),
        filled: true,
        fillColor: Colors.white,
        contentPadding: const EdgeInsets.symmetric(horizontal: 14, vertical: 13),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(10),
          borderSide: const BorderSide(color: Color(0xFFE2E8F0)),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(10),
          borderSide: const BorderSide(color: Color(0xFFE2E8F0)),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(10),
          borderSide: const BorderSide(color: Color(0xFF0F3995), width: 1.5),
        ),
        errorBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(10),
          borderSide: const BorderSide(color: Color(0xFFEF4444)),
        ),
      ),
    );
  }

  Widget _buildDropdownRow({
    required String value,
    required List<String> items,
    required void Function(String?) onChanged,
    required Color color,
  }) {
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 4),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(10),
        border: Border.all(color: const Color(0xFFE2E8F0)),
      ),
      child: DropdownButtonHideUnderline(
        child: DropdownButton<String>(
          value: value,
          isExpanded: true,
          icon: const Icon(Icons.keyboard_arrow_down, color: Color(0xFF94A3B8)),
          items: items.map((item) => DropdownMenuItem(
            value: item,
            child: Text(
              item,
              style: TextStyle(
                fontSize: 14,
                fontWeight: FontWeight.w600,
                color: item == value ? color : const Color(0xFF374151),
              ),
            ),
          )).toList(),
          onChanged: onChanged,
        ),
      ),
    );
  }

  Color _familleColor(String famille) {
    switch (famille) {
      case 'Carrelage':   return const Color(0xFFB45309);
      case 'Peinture':    return const Color(0xFF7C3AED);
      case 'Plomberie':   return const Color(0xFF0369A1);
      case 'Electricité': return const Color(0xFFD97706);
      case 'Menuiserie':  return const Color(0xFF166534);
      case 'Démolition':  return const Color(0xFFB91C1C);
      default:            return const Color(0xFF475569);
    }
  }
}
